const STRINGS = { zh, en };

// 資料庫裡的中文分類 → 英文顯示
const CATEGORY_EN = {
  餐飲: 'Food', 交通: 'Transport', 娛樂: 'Fun', 購物: 'Shopping', 學習: 'Study',
  生活: 'Living', 其他: 'Other', 零用錢: 'Allowance', 收入: 'Income', 還款: 'Repayment',
};

const WEEKDAYS = { zh: '日一二三四五六'.split(''), en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'] };

function initialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch { /* 無痕模式等情況讀不到，就看瀏覽器語言 */ }
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export let lang = initialLang();

export function setLang(next) {
  lang = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* 只是記住偏好，失敗也沒關係 */ }
  document.documentElement.lang = next === 'zh' ? 'zh-Hant' : 'en';
  document.title = t('appName');
  // 加入主畫面時圖示下面的名字（太長會被 iPhone 截掉）
  document.querySelector('meta[name="apple-mobile-web-app-title"]')?.setAttribute('content', t('homeScreenName'));
}

export function t(key, ...args) {
  const value = STRINGS[lang][key] ?? zh[key];
  return typeof value === 'function' ? value(...args) : value;
}

export const category = (c) => (lang === 'en' ? CATEGORY_EN[c] ?? c : c);
export const weekday = (i) => WEEKDAYS[lang][i];

setLang(lang);
